/**
 * Generates src/lib/practice-raga-parent-index.ts from dataset.json
 * for rāgas in the practice / scale-quiz pool that lack melakartaNum.
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataset = JSON.parse(
  readFileSync(join(root, "data/raga-scales/dataset.json"), "utf8"),
);

function norm(s) {
  return String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

/** @type {Map<string, { melakarta_num: number, is_melakarta: boolean }>} */
const byNorm = new Map();
for (const r of dataset.ragas) {
  const k = norm(r.name);
  if (!k) continue;
  const cur = byNorm.get(k);
  if (!cur || (r.melakarta_num != null && cur.melakarta_num == null)) {
    byNorm.set(k, {
      melakarta_num: r.melakarta_num ?? null,
      is_melakarta: Boolean(r.is_melakarta),
    });
  }
}

/** Pool ids: parse override keys + known quiz lists (lightweight regex). */
const overrideSrc = readFileSync(
  join(root, "src/lib/scale-quiz-scale-overrides.ts"),
  "utf8",
);
const poolIds = new Set();
for (const m of overrideSrc.matchAll(/^\s+([A-Za-z][A-Za-z0-9_]*):\s*\{/gm)) {
  poolIds.add(m[1]);
}
for (const m of readFileSync(join(root, "src/lib/raga-quiz-ragas.ts"), "utf8").matchAll(
  /id:\s*"([^"]+)"/g,
)) {
  poolIds.add(m[1]);
}

/** Curated overrides (pool id → parent). Parsed from TS without a TS runner. */
const overrideSrcPath = join(root, "src/lib/practice-raga-parent-overrides.ts");
const manualSrc = readFileSync(overrideSrcPath, "utf8");
/** @type {Record<string, { parentMelakartaNum: number; isMelakarta?: boolean }>} */
const manual = {};
for (const m of manualSrc.matchAll(
  /^\s+([A-Za-z][A-Za-z0-9_]*):\s*\{\s*parentMelakartaNum:\s*(\d+)(?:,\s*isMelakarta:\s*(true|false))?\s*\}/gm,
)) {
  manual[m[1]] = {
    parentMelakartaNum: Number(m[2]),
    isMelakarta: m[3] === "true",
  };
}

/** @type {Record<string, { parentMelakartaNum: number; isMelakarta: boolean }>} */
const index = {};
for (const id of poolIds) {
  const hit = byNorm.get(norm(id));
  if (hit?.melakarta_num != null) {
    index[id] = {
      parentMelakartaNum: hit.melakarta_num,
      isMelakarta: hit.is_melakarta,
    };
  }
}
for (const [id, o] of Object.entries(manual)) {
  index[id] = {
    parentMelakartaNum: o.parentMelakartaNum,
    isMelakarta: o.isMelakarta ?? false,
  };
}

const outPath = join(root, "src/lib/practice-raga-parent-index.ts");
const body = `/** Auto-generated by scripts/build-practice-raga-metadata.mjs — do not edit. */
export type PracticeRagaParentEntry = {
  parentMelakartaNum: number;
  isMelakarta: boolean;
};

/** Dataset fallback when \`melakartaNum\` is null on pool rāgas. */
export const PRACTICE_RAGA_PARENT_INDEX: Readonly<
  Record<string, PracticeRagaParentEntry>
> = ${JSON.stringify(index, null, 2)} as const;
`;
writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${Object.keys(index).length} entries → ${outPath}`);
